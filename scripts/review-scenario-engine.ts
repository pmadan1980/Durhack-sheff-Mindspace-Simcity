/** Review the backend directly without editing any app screen. Prints Markdown. */
import { compareDecisions, evaluateDecision, listScenarios, reflectOnDecision, type DecisionInput } from "../src/engine";

const input: DecisionInput = {
  scenarioId: "test-and-invitation", availableMinutes: 300, reservedMinutes: 60,
  facts: {
    prepared: { value: false, source: "hypothetical" },
    restorative: { value: true, source: "hypothetical" },
    canLeaveEarly: { value: true, source: "hypothetical" },
  },
  estimates: Object.fromEntries(([['prepare', 120], ['attend', 180], ['brief', 180]] as const).map(([id, minutes]) =>
    [id, { minutes, source: "hypothetical", includesTravelAndSetup: true }])),
};
const alternative = structuredClone(input);
alternative.facts.prepared.value = true;
const comparison = compareDecisions(input, alternative);
const impossible = evaluateDecision({ ...input, availableMinutes: 60 });
const reflection = reflectOnDecision(input, { chosenOptionId: "prepare", observation: "Demo reflection: I tried the plan. No additional facts recorded." });

const lines = [
  "# MINDSPACE backend review output", "",
  "Generated by the TypeScript engine. All example inputs are hypothetical. No frontend changes are needed to run this review.", "",
  "## Catalogue", "", "| Scenario | Options |", "|---|---|",
  ...listScenarios().map((s) => `| ${s.title} | ${s.options.map((o) => o.label).join('; ')} |`),
  "", "## Change one fact", "",
  "Available time: 300 minutes. Protected commitments: 60 minutes. Complete plan estimates: prepare 120, attend 180, brief visit 180. Both comparisons use the same duration estimates. Only preparation-complete changes from false to true.", "",
  "| Resident | Before | After |", "|---|---|---|",
  ...comparison.before.ballots.map((b) => `| ${b.resident} | ${b.choice ?? 'abstain (tie or no feasible option)'} | ${comparison.after.ballots.find((a) => a.resident === b.resident)!.choice ?? 'abstain'} |`),
  "", "Achievement's updated explanation:", "",
  comparison.after.arguments.find((a) => a.id === "opening-achievement")!.text,
  "", "## Impossible schedule", "",
  `With only 60 available minutes and 60 protected minutes: ${impossible.assessments.filter((a) => a.status === 'infeasible').length} infeasible options, ${impossible.abstentions} abstentions, ${impossible.alternatives.length} proposed alternatives.`,
  "", "## Reflection without new facts", "", reflection.explanation,
  `Changed ballots: ${reflection.changedBallots.length}.`,
  "", "## Limits", "", ...comparison.before.caveats.map((text) => `- ${text}`),
];
console.log(lines.join("\n"));
